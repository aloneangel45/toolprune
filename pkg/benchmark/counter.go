package benchmark

import (
	"encoding/json"
	"fmt"
	"sync"

	"github.com/aloneangel45/toolprune/pkg/mcp"
	"github.com/pkoukk/tiktoken-go"
)

const (
	// DefaultEncoding is the standard OpenAI BPE encoding used by modern LLMs.
	DefaultEncoding = "cl100k_base"
)

var (
	encoderOnce sync.Once
	encoderMu   sync.RWMutex
	encoder     *tiktoken.Tiktoken
	encoderErr  error
)

// getOrInitEncoder initializes or returns the singleton tiktoken cl100k encoder.
func getOrInitEncoder() (*tiktoken.Tiktoken, error) {
	encoderOnce.Do(func() {
		encoderMu.Lock()
		defer encoderMu.Unlock()
		enc, err := tiktoken.GetEncoding(DefaultEncoding)
		if err != nil {
			encoderErr = fmt.Errorf("failed to load tiktoken encoding %q: %w", DefaultEncoding, err)
			return
		}
		encoder = enc
	})

	encoderMu.RLock()
	defer encoderMu.RUnlock()
	return encoder, encoderErr
}

// IsExactAvailable returns true if the exact cl100k BPE encoder is loaded and ready.
func IsExactAvailable() bool {
	enc, err := getOrInitEncoder()
	return err == nil && enc != nil
}

// ResetEncoder resets the singleton encoder (primarily used in tests).
func ResetEncoder() {
	encoderMu.Lock()
	defer encoderMu.Unlock()
	encoderOnce = sync.Once{}
	encoder = nil
	encoderErr = nil
}

// CountTokens returns the exact cl100k BPE token count for the given string content.
// If the exact tokenizer is unavailable (e.g. offline first-run), it gracefully
// falls back to the calibrated estimator.
func CountTokens(content string) (int, error) {
	if content == "" {
		return 0, nil
	}

	enc, err := getOrInitEncoder()
	if err != nil {
		// Graceful fallback to calibrated fast estimator
		return EstimateTokens(content), nil
	}

	tokens := enc.Encode(content, nil, nil)
	return len(tokens), nil
}

// CountTokensExact returns the exact cl100k BPE token count or an error if the encoder is unavailable.
func CountTokensExact(content string) (int, error) {
	if content == "" {
		return 0, nil
	}

	enc, err := getOrInitEncoder()
	if err != nil {
		return 0, err
	}

	tokens := enc.Encode(content, nil, nil)
	return len(tokens), nil
}

// CountToolTokens returns the exact cl100k BPE token count for an individual tool schema.
func CountToolTokens(tool mcp.Tool) (int, error) {
	b, err := json.Marshal(tool)
	if err != nil {
		return 0, fmt.Errorf("failed to marshal tool %q: %w", tool.Name, err)
	}
	return CountTokens(string(b))
}

// CountToolsTokens returns the exact cl100k BPE token count for a slice of tools.
func CountToolsTokens(tools []mcp.Tool) (int, error) {
	if len(tools) == 0 {
		return 0, nil
	}
	b, err := json.Marshal(tools)
	if err != nil {
		return 0, fmt.Errorf("failed to marshal tools slice: %w", err)
	}
	return CountTokens(string(b))
}

// Tokenize returns the raw token IDs generated by the cl100k BPE tokenizer.
func Tokenize(content string) ([]int, error) {
	if content == "" {
		return nil, nil
	}

	enc, err := getOrInitEncoder()
	if err != nil {
		return nil, err
	}

	return enc.Encode(content, nil, nil), nil
}
